#!/usr/bin/env python3
"""Offline regression for the iPhone-reported 0.1.6 conditional failure.

Run from either a checkout or the extracted source ZIP. The frozen fixture was
extracted from the released 0.1.6 plist, not generated by the current builder.
The external exported IF supplies independent attachment/type schema evidence.
No Git, network, signing credentials, iOS runtime or third-party package is used.
"""

import argparse
import copy
import hashlib
import importlib.util
import json
from pathlib import Path
import plistlib
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "scripts/shortcut/fixtures/ios016-condition-regression.json"
SOURCE = ROOT / "scripts/shortcut/FileFlash.unsigned.plist"
PREFIX = "is.workflow.actions."
VECTORS = [("complete", True)] + [(value, False) for value in (
    "", "error", "Complete", "COMPLETE", "complete\n", "\ncomplete",
    "complete\r\n", "complete\r", "complete\t", "\tcomplete", "complete ",
    " complete", " complete ", "incomplete", "completed", "completecomplete",
    "xcomplete", "completex", "complete\nx", "complete\0", "\0complete",
    "complete\u2028", "\ufeffcomplete", "{\"status\":\"complete\"}",
)]


class SchemaError(ValueError):
    pass


def require(condition, message):
    if not condition:
        raise SchemaError(message)


def parameters(action):
    return action["WFWorkflowActionParameters"]


def identifier(action):
    return action["WFWorkflowActionIdentifier"]


def actions(document):
    return document["WFWorkflowActions"]


def conditional_input(action):
    """The nested Variable wrapper is present in the project-published export.

    This is intentionally distinct from a text/file action's bare attachment.
    Do not flatten it while repairing the right-operand/type problem.
    """
    value = parameters(action).get("WFInput", {})
    require(set(value) == {"Type", "Variable"} and value["Type"] == "Variable",
            "IF input must retain the exported Variable wrapper")
    attachment = value["Variable"]
    require(set(attachment) == {"Value", "WFSerializationType"} and
            attachment["WFSerializationType"] == "WFTextTokenAttachment",
            "IF Variable must contain a token attachment")
    require(type(attachment["Value"]) is dict, "IF attachment has no variable value")
    return attachment["Value"]


def reject_untyped_dictionary_comparison(document):
    by_id = {parameters(a).get("UUID"): a for a in actions(document)}
    for action in actions(document):
        p = parameters(action)
        if identifier(action) != PREFIX + "conditional" or p.get("WFControlFlowMode") != 0:
            continue
        left = conditional_input(action)
        producer = by_id.get(left.get("OutputUUID"))
        if not producer or identifier(producer) != PREFIX + "getvalueforkey":
            continue
        if "WFConditionalActionString" not in p:
            continue
        typed_text = any(item.get("Type") == "WFCoercionVariableAggrandizement" and
                         item.get("CoercionItemClass") == "WFStringContentItem"
                         for item in left.get("Aggrandizements", []))
        require(typed_text, "Untyped dictionary-value IF has a string right operand")


def completion_chain(document):
    """Locate the status-to-predicate chain by dataflow, without builder UUIDs."""
    reject_untyped_dictionary_comparison(document)
    status = [a for a in actions(document)
              if identifier(a) == PREFIX + "getvalueforkey" and
              parameters(a).get("WFDictionaryKey") == "status"]
    require(len(status) == 1, "Expected one upload status producer")
    status_id = parameters(status[0])["UUID"]
    matches = []
    for action in actions(document):
        if identifier(action) != PREFIX + "text.match":
            continue
        token = parameters(action).get("text", {})
        if token.get("WFSerializationType") != "WFTextTokenString":
            continue
        value = token.get("Value", {})
        references = value.get("attachmentsByRange", {})
        if value.get("string") == "\ufffc" and set(references) == {"{0, 1}"}:
            reference = references["{0, 1}"]
            if reference.get("Type") == "ActionOutput" and reference.get("OutputUUID") == status_id:
                matches.append(action)
    require(len(matches) == 1, "Status must enter one explicit text-token match")
    match = matches[0]
    match_id = parameters(match)["UUID"]
    consumers = [a for a in actions(document)
                 if identifier(a) == PREFIX + "conditional" and
                 parameters(a).get("WFControlFlowMode") == 0 and
                 conditional_input(a).get("OutputUUID") == match_id]
    require(len(consumers) == 1, "Match must feed one IF")
    condition = parameters(consumers[0])
    require(condition.get("WFCondition") == 101,
            "Failed completion must use a no-value predicate")
    require("WFConditionalActionString" not in condition and "WFNumberValue" not in condition,
            "Completion IF must not need a second operand")
    return match, consumers[0]


def acceptance(document):
    match, _ = completion_chain(document)
    p = parameters(match)
    flags = 0 if p.get("WFMatchTextCaseSensitive") is True else re.IGNORECASE
    try:
        expression = re.compile(p["WFMatchTextPattern"], flags)
    except (KeyError, re.error) as error:
        raise SchemaError("Invalid completion regular expression") from error
    return [(value, bool(expression.search(value)), expected) for value, expected in VECTORS]


def check_acceptance(document):
    result = acceptance(document)
    for value, actual, expected in result:
        require(actual is expected, "Wrong completion outcome for " + repr(value))
    return result


def network_and_effects(document, fixture):
    current = [a for a in actions(document) if identifier(a) == PREFIX + "downloadurl"]
    # This baseline equality protects actual endpoints, headers, body variables,
    # session release and file representation; the 0.1.7 repair is predicate-only.
    require(json.dumps(current, sort_keys=True) == json.dumps(fixture["networkActions"], sort_keys=True),
            "Network destinations or body/header/credential flow changed from 0.1.6")
    unexpected = set(identifier(a) for a in actions(document)) - set(fixture["allowedActionIdentifiers"])
    require(not unexpected, "A new action could add persistence, conversion or external effects: " + str(unexpected))


def must_reject(function, value, *args):
    try:
        function(value, *args)
    except SchemaError:
        return
    raise AssertionError("Invalid regression variant was accepted")


def load_builder():
    spec = importlib.util.spec_from_file_location("fileflash_shortcut_builder_regression",
                                               ROOT / "scripts/build-ios-shortcut.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--unsigned", type=Path, default=SOURCE)
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    fixture_bytes = FIXTURE.read_bytes()
    fixture = json.loads(fixture_bytes)
    source_bytes = args.unsigned.read_bytes()
    current = plistlib.loads(source_bytes)
    builder = load_builder()
    checks = []

    def test(name, callback):
        try:
            callback()
            checks.append({"name": name, "passed": True})
        except Exception as error:
            checks.append({"name": name, "passed": False,
                           "error": type(error).__name__ + ": " + str(error)})

    def provenance():
        p = fixture["releaseProvenance"]
        require(p["commit"] == "f978a563bbea05ec5f3d7b82ad0a12d0bb7c6fc6" and
                p["sourceSha256"] == "34b469c13b25eb6d8ecb3265b6d71f72118d5718aa0ef8aff2bac0725ad56d66",
                "Fixture provenance is not the released 0.1.6 source")
        legacy = actions(fixture["releasedFailingWorkflow"])[1]
        require(parameters(legacy).get("WFConditionalActionString") == "complete",
                "The historical failure contained complete in its plist; do not model it as merely absent")
        require(not conditional_input(legacy).get("Aggrandizements"),
                "The historical comparison must remain untyped")

    def external_export():
        sample = fixture["exportedSchemaReference"]["action"]
        left = conditional_input(sample)
        require(any(item.get("CoercionItemClass") == "WFStringContentItem"
                    for item in left.get("Aggrandizements", [])), "Exported comparison has no text coercion")
        require(parameters(sample).get("WFConditionalActionString") == "exception",
                "External exported comparison changed")

    def production_guard_rejects_release():
        try:
            builder.validate_conditions(fixture["releasedFailingWorkflow"])
        except ValueError:
            return
        raise AssertionError("Production guard accepted the released untyped comparison")

    def old_wrappers_preserved():
        by_id = {parameters(a).get("UUID"): a for a in actions(current)}
        for old in fixture["initialIfInputs"]:
            found = by_id[old["UUID"]]
            conditional_input(found)
            require(parameters(found)["WFInput"] == old["WFInput"],
                    "A previously working input/QR/session IF attachment changed")
        for action in actions(current):
            if identifier(action) == PREFIX + "conditional" and parameters(action).get("WFControlFlowMode") == 0:
                conditional_input(action)

    def production_guard_accepts_current():
        builder.validate_conditions(current)

    test("Frozen released fixture retains the literal right value and missing input text type", provenance)
    test("Independent exported IF confirms nested token wrapper and typed string comparison", external_export)
    test("Independent schema audit rejects the released 0.1.6 comparison",
         lambda: must_reject(reject_untyped_dictionary_comparison, fixture["releasedFailingWorkflow"]))
    test("Production condition guard independently rejects the released fixture", production_guard_rejects_release)
    test("Previously working input/QR/session IF wrappers are unchanged", old_wrappers_preserved)
    test("Current status flows through text match into a no-value IF", lambda: completion_chain(current))
    test("Only exact lowercase complete is accepted across adversarial status strings", lambda: check_acceptance(current))
    test("Production condition guard accepts current source", production_guard_accepts_current)
    test("Network/body/header/session operations and effectful action vocabulary are unchanged",
         lambda: network_and_effects(current, fixture))

    def bad_pattern(pattern=None, ignore_case=False):
        changed = copy.deepcopy(current)
        match, _ = completion_chain(changed)
        if pattern is not None:
            parameters(match)["WFMatchTextPattern"] = pattern
        if ignore_case:
            parameters(match)["WFMatchTextCaseSensitive"] = False
        must_reject(check_acceptance, changed)

    test("An unanchored complete matcher is detected", lambda: bad_pattern("complete"))
    test("A dollar-end matcher that accepts a trailing newline is detected", lambda: bad_pattern("^complete$"))
    test("Case-insensitive completion matching is detected", lambda: bad_pattern(ignore_case=True))

    def flat_wrapper():
        changed = copy.deepcopy(current)
        _, condition = completion_chain(changed)
        parameters(condition)["WFInput"] = parameters(condition)["WFInput"]["Variable"]
        must_reject(completion_chain, changed)

    def bypass_match():
        changed = copy.deepcopy(current)
        _, condition = completion_chain(changed)
        legacy_input = actions(fixture["releasedFailingWorkflow"])[1]["WFWorkflowActionParameters"]["WFInput"]
        parameters(condition)["WFInput"] = copy.deepcopy(legacy_input)
        must_reject(completion_chain, changed)

    test("Flattening the exported IF attachment wrapper is detected", flat_wrapper)
    test("Bypassing the text match with the dictionary-value output is detected", bypass_match)

    def new_network_destination():
        changed = copy.deepcopy(current)
        network = copy.deepcopy(fixture["networkActions"][0])
        parameters(network)["WFURL"] = "https://example.invalid/receive"
        actions(changed).append(network)
        must_reject(network_and_effects, changed, fixture)

    def new_effect(name):
        changed = copy.deepcopy(current)
        actions(changed).append({"WFWorkflowActionIdentifier": PREFIX + name,
                                 "WFWorkflowActionParameters": {}})
        must_reject(network_and_effects, changed, fixture)

    test("Adding an external upload destination is detected", new_network_destination)
    test("Adding a local Save File persistence action is detected", lambda: new_effect("documentpicker.save"))
    test("Adding an image conversion action is detected", lambda: new_effect("image.convert"))
    results = acceptance(current) if all(item["passed"] for item in checks) else []
    report = {
        "passed": all(item["passed"] for item in checks),
        "unsignedSha256": hashlib.sha256(source_bytes).hexdigest(),
        "fixtureSha256": hashlib.sha256(fixture_bytes).hexdigest(),
        "checks": checks, "checkCount": len(checks), "actionCount": len(actions(current)),
        "statusVectors": [{"value": value, "accepted": actual, "expected": expected}
                          for value, actual, expected in results],
        "releaseFixtureProvenance": fixture["releaseProvenance"],
        "independentSchemaReference": {key: value for key, value in fixture["exportedSchemaReference"].items()
                                       if key != "action"},
        "scope": "Offline plist schema/dataflow and Python regex regression. Frozen 0.1.6 and independent exported schema fixtures; no Git or network required. Does not execute Shortcuts, iOS import, Photos, media conversion or network transfer.",
    }
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print(("PASS" if report["passed"] else "FAIL") + ": " + str(len(checks)) +
              " offline Shortcut schema regression checks; no iOS execution claim.")
        for item in checks:
            if not item["passed"]:
                print(item["name"] + ": " + item["error"], file=sys.stderr)
    else:
        print(json.dumps(report, ensure_ascii=False, indent=2))
    return 0 if report["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
